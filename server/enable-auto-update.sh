#!/usr/bin/env bash
# Update the server every night: a systemd user timer that runs server/update.sh (pull,
# rebuild and restart only when the code changed; back to the previous image if the new
# one doesn't start). Run as the service user:
#   server/enable-auto-update.sh [HH:MM]     default 02:30, before the 03:00 nightly sync
#   server/enable-auto-update.sh off
set -euo pipefail
at="${1:-02:30}"
repo="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
units="$HOME/.config/systemd/user"
mkdir -p "$units"

if [ "$at" = "off" ]; then
    systemctl --user disable --now training-analyze-update.timer 2>/dev/null || true
    rm -f "$units/training-analyze-update.timer" "$units/training-analyze-update.service"
    systemctl --user daemon-reload
    echo "Nightly update off."
    exit 0
fi
[[ "$at" =~ ^[0-2][0-9]:[0-5][0-9]$ ]] || { echo "time as HH:MM, e.g. 02:30" >&2; exit 1; }

cat > "$units/training-analyze-update.service" <<UNIT
# Generated by server/enable-auto-update.sh
[Unit]
Description=Update Training Analyze from git
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
ExecStart=$repo/server/update.sh
TimeoutStartSec=30min
UNIT

cat > "$units/training-analyze-update.timer" <<UNIT
# Generated by server/enable-auto-update.sh
[Unit]
Description=Nightly Training Analyze update

[Timer]
OnCalendar=*-*-* $at
# Run at the next boot if the server was off at that time.
Persistent=true

[Install]
WantedBy=timers.target
UNIT

systemctl --user daemon-reload
systemctl --user enable --now training-analyze-update.timer
echo "Nightly update at $at. Next run:"
systemctl --user list-timers training-analyze-update.timer --no-pager | head -2
