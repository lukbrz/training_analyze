#!/usr/bin/env bash
# Add (or update) one athlete's Training Analyze service: their data folder, password and a
# Podman quadlet unit that starts the container at boot. Run as the service user (not root):
#   server/add-athlete.sh NAME PORT [BIND_ADDRESS]
# e.g. server/add-athlete.sh lukasz 8080          (listens on all the server's addresses)
#      server/add-athlete.sh anna 8081 192.168.88.10
set -euo pipefail

name="${1:?usage: add-athlete.sh NAME PORT [BIND_ADDRESS]}"
port="${2:?usage: add-athlete.sh NAME PORT [BIND_ADDRESS]}"
bind="${3:-}"
[[ "$name" =~ ^[a-z0-9_-]+$ ]] || { echo "NAME: lowercase letters, digits, - and _ only" >&2; exit 1; }

data="$HOME/training-analyze/$name"
config="$HOME/.config/training-analyze"
units="$HOME/.config/containers/systemd"
mkdir -p "$data" "$config" "$units"

envfile="$config/$name.env"
if [ ! -f "$envfile" ]; then
    password="$(head -c 18 /dev/urandom | base64 | tr -d '/+=' | cut -c1-20)"
    umask 077
    {
        echo "# Training Analyze settings for $name (restart the service after editing)"
        echo "TA_PASSWORD=$password"
        echo "# Nightly run time and reprocess policy (when-changed | always):"
        echo "TA_NIGHTLY_AT=03:00"
        echo "TA_NIGHTLY_REPROCESS=when-changed"
    } > "$envfile"
    echo "Sign-in password for $name: $password   (kept in $envfile)"
fi

publish="${bind:+$bind:}$port:8080"
cat > "$units/training-analyze-$name.container" <<UNIT
# Generated by server/add-athlete.sh — Training Analyze for $name.
[Unit]
Description=Training Analyze ($name)
After=network-online.target
Wants=network-online.target

[Container]
Image=localhost/training-analyze:latest
ContainerName=training-analyze-$name
Volume=$data:/data
PublishPort=$publish
EnvironmentFile=$envfile
# The host account owns the data folder; inside, the app runs as uid 1000.
UserNS=keep-id:uid=1000,gid=1000
HealthCmd=python -c "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8080/health', timeout=4)"
HealthInterval=2m
HealthOnFailure=kill

[Service]
Restart=always
TimeoutStartSec=120

[Install]
WantedBy=default.target
UNIT

systemctl --user daemon-reload
systemctl --user restart "training-analyze-$name"
echo "Started training-analyze-$name on port $port — open http://<server>:$port"
